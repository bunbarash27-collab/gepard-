import type { RiskFlag } from './types';

interface RiskRule {
  re: RegExp;
  reason: string;
  safe: string;
}

const RULES: RiskRule[] = [
  { re: /100\s*%|сто процентов/i, reason: 'Абсолютное обещание результата без подтверждения', safe: 'заметная разница у многих покупателей' },
  { re: /гарант[а-яё]*/i, reason: 'Гарантия результата требует документального подтверждения', safe: 'помогает добиться результата' },
  { re: /навсегда|раз и навсегда/i, reason: 'Обещание вечного эффекта', safe: 'надолго' },
  { re: /вылеч[а-яё]*|излеч[а-яё]*|(?<![а-яё])лечит[а-яё]*|исцел[а-яё]*/i, reason: 'Медицинское обещание — товар не является лекарством', safe: 'помогает чувствовать себя комфортнее' },
  { re: /избав[а-яё]* от .{0,20}(болезн|заболеван|апноэ)/i, reason: 'Обещание избавления от заболевания', safe: 'помогает сделать сон комфортнее' },
  { re: /врачи рекоменд[а-яё]*|рекомендовано врач[а-яё]*/i, reason: 'Ссылка на рекомендацию врачей без подтверждения', safe: 'выбирают покупатели' },
  { re: /клинически доказ[а-яё]*|научно доказ[а-яё]*/i, reason: 'Ссылка на исследования без источника', safe: 'продуманная конструкция' },
  { re: /без побочных/i, reason: 'Медицинское утверждение о безопасности', safe: 'аккуратный и бережный формат' },
  { re: /мгновенн[а-яё]*|за (одну|1) (ночь|минуту|день)/i, reason: 'Обещание мгновенного результата', safe: 'с первых дней использования' },
  { re: /(самый )?(?<![а-яё])лучш[а-яё]*( в мире)?|№\s?1|номер один/i, reason: 'Превосходная степень без подтверждения (ФЗ «О рекламе»)', safe: 'один из удобных вариантов' },
  { re: /похуде[а-яё]* на \d+|минус \d+ ?кг/i, reason: 'Конкретное обещание снижения веса', safe: 'поддержка в достижении цели' },
  { re: /заработ[а-яё]* \d+|пассивн[а-яё]* доход|доход гарантир[а-яё]*/i, reason: 'Финансовое обещание', safe: 'помогает экономить время' },
  { re: /абсолютно безопас[а-яё]*/i, reason: 'Абсолютное утверждение о безопасности', safe: 'изготовлен из материалов, указанных в описании' },
];

// Cyrillic needs explicit [а-яё] classes: JS \w only matches Latin letters.
/** Finds risky advertising claims in user-provided product text. */
export function detectRisks(text: string, source: string): RiskFlag[] {
  const flags: RiskFlag[] = [];
  for (const rule of RULES) {
    const m = text.match(rule.re);
    if (m) flags.push({ phrase: m[0], source, reason: rule.reason, safeAlternative: rule.safe });
  }
  return flags;
}

export function isRisky(text: string): boolean {
  return RULES.some((r) => r.re.test(text));
}

